import '../filters/filter_condition.dart';
import '../filters/sort_condition.dart';
import 'pagination_limits.dart';

/// A keyset (cursor) paginated query.
///
/// Cursor pagination is the correct choice for infinite-scroll feeds and for
/// large, frequently mutated datasets: the database seeks directly to the
/// cursor instead of counting and discarding preceding rows, so page cost stays
/// constant.
///
/// ```dart
/// var cursor = '';
/// do {
///   final page = await sdk.products.getCursorPage(
///     request: CursorRequest(cursor: cursor.isEmpty ? null : cursor, limit: 20),
///   );
///   cursor = page.valueOrNull?.nextCursor ?? '';
/// } while (cursor.isNotEmpty);
/// ```
class CursorRequest {
  /// An opaque cursor returned by a previous page, or `null` to start.
  ///
  /// Treat the value as opaque: it is generated by the active provider and its
  /// encoding is not part of this package's public contract.
  final String? cursor;

  /// The maximum number of records to return.
  ///
  /// Must not exceed [PaginationLimits.maxCursorLimit].
  final int limit;

  /// A free-text search term.
  final String? search;

  /// Typed filters applied to the query.
  final List<FilterCondition> filters;

  /// Typed sort instructions.
  ///
  /// Cursor pagination requires a deterministic, unique ordering. The provider
  /// therefore appends the primary key as a tie-breaker when it is not already
  /// present, regardless of what is passed here.
  final List<SortCondition> sorting;

  /// Whether the exact total number of matching records should be returned.
  final bool includeTotalCount;

  /// Creates a cursor request.
  const CursorRequest({
    this.cursor,
    this.limit = PaginationLimits.defaultPageSize,
    this.search,
    this.filters = const [],
    this.sorting = const [],
    this.includeTotalCount = false,
  });

  /// Validates the numeric bounds of this request.
  ///
  /// Returns `null` when the request is valid, otherwise a developer-facing
  /// description of the problem.
  String? validate() {
    if (limit < PaginationLimits.minPageSize) {
      return 'limit must be at least ${PaginationLimits.minPageSize}, '
          'but was $limit.';
    }
    if (limit > PaginationLimits.maxCursorLimit) {
      return 'limit must not exceed ${PaginationLimits.maxCursorLimit}, '
          'but was $limit.';
    }
    return null;
  }

  /// A stable identity for this request, used to de-duplicate concurrent loads.
  String get cacheKey => [
        'cursor:${cursor ?? ''}',
        'limit:$limit',
        'search:${search ?? ''}',
        'count:$includeTotalCount',
        for (final filter in filters) filter.cacheKey,
        for (final sort in sorting) sort.cacheKey,
      ].join('|');

  /// Returns a copy of this request with the given fields replaced.
  CursorRequest copyWith({
    String? cursor,
    int? limit,
    String? search,
    List<FilterCondition>? filters,
    List<SortCondition>? sorting,
    bool? includeTotalCount,
  }) {
    return CursorRequest(
      cursor: cursor ?? this.cursor,
      limit: limit ?? this.limit,
      search: search ?? this.search,
      filters: filters ?? this.filters,
      sorting: sorting ?? this.sorting,
      includeTotalCount: includeTotalCount ?? this.includeTotalCount,
    );
  }

  @override
  String toString() {
    return 'CursorRequest(cursor: ${cursor == null ? 'null' : '***'}, '
        'limit: $limit, search: $search, filters: ${filters.length})';
  }
}
